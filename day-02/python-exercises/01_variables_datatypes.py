# Python Variables and Data Types

name = "Samruddhi"
age = 21
city = "Nagpur"
percentage = 85.5
is_intern = True

print("Name:", name)
print("Age:", age)
print("City:", city)
print("Percentage:", percentage)
print("Intern:", is_intern)

print("\nData Types:")
print("name:", type(name))
print("age:", type(age))
print("city:", type(city))
print("percentage:", type(percentage))
print("is_intern:", type(is_intern))