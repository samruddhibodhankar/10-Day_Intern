# Python Lists, Tuples, Sets and Dictionaries

# List
subjects = ["Python", "SQL", "DSA"]
print("List:", subjects)

# Tuple
marks = (85, 90, 88)
print("Tuple:", marks)

# Set
skills = {"Python", "SQL", "Python"}
print("Set:", skills)

# Dictionary
student = {
    "name": "Samruddhi",
    "age": 21,
    "percentage": 85.5
}
print("Dictionary:", student)